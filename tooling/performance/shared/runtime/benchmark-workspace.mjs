import { randomUUID } from "node:crypto";
import {
  lstat,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  realpath,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { benchmarkComparison } from "../constants/benchmark-comparison.constant.mjs";

/** @description Owns bounded disposable fixture files without following junctions during cleanup. */
export class BenchmarkWorkspace {
  /** @description Unexported acquisition key restricting construction to the owning factory. */
  static #creationKey = Symbol("benchmark-workspace-acquisition");
  /** @description Physical system-temporary root owned by this instance. */
  #root;
  /** @description Ownership token required before publication or recursive cleanup. */
  #token;
  /** @description Bytes written through this instance, indexed by contained relative path. */
  #files = new Map();
  /** @description Total successfully published owned content bytes. */
  #bytes = 0;
  /** @description Maximum owned file count. */
  #maximumFiles;
  /** @description Maximum owned content bytes. */
  #maximumBytes;

  /**
   * @description Creates an instance for a newly acquired ownership-marked root.
   * @param {string} root - Newly created physical temporary directory.
   * @param {string} token - Unique ownership token.
   * @param {{ maximumFiles: number, maximumBytes: number }} limits - Explicit publication budgets.
   * @param {symbol} creationKey - Private acquisition authority.
   */
  constructor(root, token, limits, creationKey) {
    if (creationKey !== BenchmarkWorkspace.#creationKey) {
      throw new TypeError(
        "Use BenchmarkWorkspace.create to acquire an owned root.",
      );
    }
    this.#root = root;
    this.#token = token;
    this.#maximumFiles = limits.maximumFiles;
    this.#maximumBytes = limits.maximumBytes;
  }

  /**
   * @description Acquires an ownership-marked system temporary directory with finite budgets.
   * @param {{ maximumFiles?: number, maximumBytes?: number }} [limits] - Optional smaller or explicitly chosen budgets.
   * @returns {Promise<BenchmarkWorkspace>} Owned disposable workspace.
   */
  static async create(limits = {}) {
    const maximumFiles =
      limits.maximumFiles ?? benchmarkComparison.maximumFiles;
    const maximumBytes =
      limits.maximumBytes ?? benchmarkComparison.maximumWorkspaceBytes;
    if (
      ![maximumFiles, maximumBytes].every(
        (value) => Number.isSafeInteger(value) && value > 0,
      ) ||
      maximumFiles > benchmarkComparison.maximumFiles ||
      maximumBytes > benchmarkComparison.maximumWorkspaceBytes
    ) {
      throw new TypeError("Invalid benchmark workspace budget.");
    }
    const root = await realpath(
      await mkdtemp(join(tmpdir(), "aster-benchmark-")),
    );
    const token = randomUUID();
    try {
      await writeFile(join(root, ".benchmark-owner"), token, { flag: "wx" });
      return new BenchmarkWorkspace(
        root,
        token,
        { maximumFiles, maximumBytes },
        BenchmarkWorkspace.#creationKey,
      );
    } catch (error) {
      await rm(root, { recursive: true, force: true });
      throw error;
    }
  }

  /**
   * @description Returns the owned physical root, never an external dependency target.
   * @returns {string} Absolute root.
   */
  get root() {
    return this.#root;
  }

  /**
   * @description Publishes one contained fixture file without traversing an existing symbolic link.
   * @param {string} path - Relative path below the owned root.
   * @param {string | Uint8Array} content - Exact generated bytes.
   * @returns {Promise<string>} Published absolute path.
   */
  async write(path, content) {
    await this.#assertOwner();
    const target = this.#contained(path);
    const bytes =
      typeof content === "string"
        ? Buffer.byteLength(content)
        : content.byteLength;
    const total = this.#bytes - (this.#files.get(target) ?? 0) + bytes;
    if (
      (!this.#files.has(target) && this.#files.size >= this.#maximumFiles) ||
      total > this.#maximumBytes
    ) {
      throw new Error("Benchmark workspace budget exceeded.");
    }
    await this.#assertNoLinks(target);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
    this.#files.set(target, bytes);
    this.#bytes = total;
    return target;
  }

  /**
   * @description Copies a built package into an independent fixture module graph through bounded publication.
   * @param {string} path - Contained destination package path.
   * @param {string} packageRoot - Physical source package whose manifest and dist are read only; dependency acquisition is separate.
   * @returns {Promise<string>} Independent package directory, suitable for a genuine separate Core copy.
   */
  async copyPackage(path, packageRoot) {
    const source = await realpath(packageRoot);
    this.#contained(path);
    await this.write(
      `${path}/package.json`,
      await readFile(join(source, "package.json")),
    );
    await this.#copyDirectory(join(source, "dist"), `${path}/dist`);
    return resolve(this.#root, path);
  }

  /**
   * @description Removes an owned root only after validating ownership, never following descendant junctions.
   * @remarks Nested symbolic links are rejected before recursive removal. Remove such a link explicitly and retry; no external target is removed.
   * @returns {Promise<void>} Nothing after successful cleanup.
   */
  async dispose() {
    await this.#assertOwner();
    await this.#assertTree(this.#root);
    await rm(this.#root, { recursive: true, force: false });
  }

  /**
   * @description Rejects root replacement or ownership-marker substitution before effects.
   * @returns {Promise<void>} Nothing after ownership agreement.
   */
  async #assertOwner() {
    const root = await lstat(this.#root);
    const marker = join(this.#root, ".benchmark-owner");
    if (
      root.isSymbolicLink() ||
      !root.isDirectory() ||
      (await lstat(marker)).isSymbolicLink() ||
      (await realpath(this.#root)) !== this.#root ||
      (await readFile(marker, "utf8")) !== this.#token
    ) {
      throw new Error("Benchmark workspace ownership changed.");
    }
  }

  /**
   * @description Resolves a non-empty relative file path within the owned boundary.
   * @param {string} path - Relative fixture path.
   * @returns {string} Contained absolute path.
   */
  #contained(path) {
    const target = resolve(this.#root, path);
    const relation = relative(this.#root, target);
    if (
      path.length === 0 ||
      isAbsolute(path) ||
      relation === "" ||
      relation === ".." ||
      relation.startsWith(`..${sep}`) ||
      isAbsolute(relation) ||
      path.split(/[\\/]/u).includes("..") ||
      relation === ".benchmark-owner"
    ) {
      throw new Error("Benchmark path escapes its owned file boundary.");
    }
    return target;
  }

  /**
   * @description Rejects a symbolic link at any existing component of one contained destination.
   * @param {string} target - Previously contained destination.
   * @returns {Promise<void>} Nothing when existing components are physical entries.
   */
  async #assertNoLinks(target) {
    let current = this.#root;
    for (const part of relative(this.#root, target).split(sep)) {
      current = join(current, part);
      try {
        if ((await lstat(current)).isSymbolicLink()) {
          throw new Error("Benchmark paths must not traverse symbolic links.");
        }
      } catch (error) {
        if (!(
          error instanceof Error &&
          "code" in error &&
          error.code === "ENOENT"
        )) {
          throw error;
        }
      }
    }
  }

  /**
   * @description Reads a finite physical distribution tree without following source links.
   * @param {string} source - Physical source directory.
   * @param {string} destination - Contained relative destination.
   * @returns {Promise<void>} Nothing after bounded copying.
   */
  async #copyDirectory(source, destination) {
    if ((await lstat(source)).isSymbolicLink()) {
      throw new Error("Benchmark copies must not traverse symbolic links.");
    }
    for (const entry of await readdir(source, { withFileTypes: true })) {
      if (entry.isSymbolicLink() || (!entry.isDirectory() && !entry.isFile())) {
        throw new Error(
          "Benchmark copies require physical files and directories.",
        );
      }
      if (entry.isDirectory()) {
        await this.#copyDirectory(
          join(source, entry.name),
          `${destination}/${entry.name}`,
        );
      } else {
        await this.write(
          `${destination}/${entry.name}`,
          await readFile(join(source, entry.name)),
        );
      }
    }
  }

  /**
   * @description Validates every descendant before recursive cleanup of the owned root.
   * @param {string} directory - Physical directory already inside the owned root.
   * @returns {Promise<void>} Nothing if no junction or symbolic link is present.
   */
  async #assertTree(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) {
        throw new Error("Benchmark cleanup refuses symbolic links.");
      }
      if (entry.isDirectory()) {
        await this.#assertTree(join(directory, entry.name));
      }
    }
  }
}
