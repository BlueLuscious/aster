import { Icon } from "@luscious-garden/aster-core";
import { pathToFileURL } from "node:url";

/** @description Produces explicit synthetic leaf/dictionary modules, not product Icons distribution. */
export class BenchmarkModuleFixtureFactory {
  /**
   * @description Writes one module per concrete identity and a separate dictionary per glyph.
   * @param {import("../../shared/runtime/benchmark-workspace.mjs").BenchmarkWorkspace} workspace - Owned bounded publication capability.
   * @param {readonly import("@luscious-garden/aster-core").IconDefinition[]} icons - Canonical concrete synthetic definitions.
   * @param {string} coreModuleUrl - Explicit Core module URL shared by generated leaves.
   * @returns {Promise<{ leaves: readonly string[], glyphs: readonly string[], definitions: number, distinctGlyphs: number }>} Distinct module URLs, without cached duplicates.
   */
  async create(workspace, icons, coreModuleUrl) {
    if (new URL(coreModuleUrl).protocol !== "file:") {
      throw new TypeError(
        "Synthetic modules require an explicit local Core URL.",
      );
    }
    const identities = new Set();
    /** @type {Map<string, { property: string, ordinal: number }[]>} */
    const groups = new Map();
    const leaves = [];
    for (const [ordinal, icon] of icons.entries()) {
      const identity = JSON.stringify(icon.identity);
      if (identities.has(identity) || Icon.define(icon) !== icon) {
        throw new TypeError(
          "Synthetic modules require distinct local canonical definitions.",
        );
      }
      identities.add(identity);
      const key = JSON.stringify([
        icon.identity.namespace ?? null,
        icon.identity.name,
      ]);
      const group = groups.get(key) ?? [];
      const property = Icon.variantPropertyName(icon.identity.variant);
      if (group.some((entry) => entry.property === property)) {
        throw new TypeError("Synthetic module variant properties collide.");
      }
      group.push({ property, ordinal });
      groups.set(key, group);
      const path = await workspace.write(
        `dist/icons/leaf-${ordinal}.mjs`,
        `// Generated by tooling/performance/icons/runtime/benchmark-module-fixture.factory.mjs from prepared synthetic definitions.\nimport { Icon } from ${JSON.stringify(coreModuleUrl)};\nexport const definition = Icon.define(${JSON.stringify(icon)});\n`,
      );
      leaves.push(pathToFileURL(path).href);
    }
    const glyphs = [];
    for (const [ordinal, group] of [...groups.values()].entries()) {
      const imports = group
        .map(
          (entry) =>
            `import { definition as variant${entry.ordinal} } from "../icons/leaf-${entry.ordinal}.mjs";`,
        )
        .join("\n");
      const entries = group
        .map(
          (entry) =>
            `${JSON.stringify(entry.property)}: variant${entry.ordinal}`,
        )
        .join(", ");
      const path = await workspace.write(
        `dist/glyphs/glyph-${ordinal}.mjs`,
        `// Generated by tooling/performance/icons/runtime/benchmark-module-fixture.factory.mjs from prepared synthetic definitions.\n${imports}\nexport const variants = Object.freeze({ ${entries} });\n`,
      );
      glyphs.push(pathToFileURL(path).href);
    }
    return Object.freeze({
      leaves: Object.freeze(leaves),
      glyphs: Object.freeze(glyphs),
      definitions: leaves.length,
      distinctGlyphs: glyphs.length,
    });
  }
}
